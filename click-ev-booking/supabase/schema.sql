create or replace function public.click_reconcile_station(p_station_id integer)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_station public.charging_stations%rowtype;
begin
  select * into v_station
  from public.charging_stations
  where id = p_station_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Station not found';
  end if;

  if v_station.slot_status = 'Buffer'
     and v_station.buffer_end_time is not null
     and v_station.buffer_end_time <= now() then
    update public.charging_stations
    set slot_status = 'Available',
        relay_status = false,
        current_rider = null,
        next_rider = null,
        buffer_end_time = null,
        charge_started_at = null,
        updated_at = now()
    where id = p_station_id
    returning * into v_station;
  elsif v_station.slot_status = 'Reserved'
        and v_station.buffer_end_time is not null
        and v_station.buffer_end_time + interval '10 minutes' <= now() then
    if coalesce(v_station.next_rider, v_station.current_rider) is not null then
      insert into public.rider_penalties (
        station_id, rider_name, rider_name_key, reason, penalty_until
      ) values (
        v_station.id,
        coalesce(v_station.next_rider, v_station.current_rider),
        lower(btrim(coalesce(v_station.next_rider, v_station.current_rider))),
        'No-show: did not start within 10 minutes of the scheduled slot',
        now() + interval '10 minutes'
      );
    end if;

    update public.charging_stations
    set slot_status = 'Available',
        relay_status = false,
        current_rider = null,
        next_rider = null,
        buffer_end_time = null,
        slot_start_time = null,
        slot_end_time = null,
        charge_started_at = null,
        no_show_count = no_show_count + 1,
        penalty_status = true,
        updated_at = now()
    where id = p_station_id
    returning * into v_station;
  end if;

  return to_jsonb(v_station);
end;
$$;

create or replace function public.click_book_station(
  p_station_id integer,
  p_rider_name text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_station public.charging_stations%rowtype;
  v_penalty_until timestamptz;
  v_rider_name text := btrim(p_rider_name);
  v_rider_key text := lower(btrim(p_rider_name));
  v_action text;
  v_message text;
begin
  perform public.click_reconcile_station(p_station_id);

  select * into v_station
  from public.charging_stations
  where id = p_station_id
  for update;

  select max(penalty_until) into v_penalty_until
  from public.rider_penalties
  where rider_name_key = v_rider_key
    and penalty_until > now();

  if v_penalty_until is not null then
    raise exception using errcode = 'P0001',
      message = 'No-show cooldown is active until ' || v_penalty_until::text;
  end if;

  if v_station.slot_status = 'Available' then
    update public.charging_stations
    set slot_status = 'Charging',
        relay_status = true,
        current_rider = v_rider_name,
        next_rider = null,
        buffer_end_time = null,
        slot_start_time = now(),
        slot_end_time = null,
        charge_started_at = now(),
        penalty_status = false,
        updated_at = now()
    where id = p_station_id
    returning * into v_station;
    v_action := 'started';
    v_message := 'Charging started. The socket relay is on.';
  elsif v_station.slot_status = 'Buffer' then
    update public.charging_stations
    set slot_status = 'Reserved',
        relay_status = false,
        current_rider = null,
        next_rider = v_rider_name,
        slot_start_time = v_station.buffer_end_time,
        slot_end_time = null,
        charge_started_at = null,
        penalty_status = false,
        updated_at = now()
    where id = p_station_id
    returning * into v_station;
    v_action := 'reserved';
    v_message := 'Slot reserved. Power remains off until the 10-minute transition window ends.';
  else
    raise exception using errcode = 'P0001',
      message = 'This charging slot is already occupied or reserved.';
  end if;

  return jsonb_build_object(
    'station', to_jsonb(v_station),
    'action', v_action,
    'message', v_message
  );
end;
$$;

create or replace function public.click_start_reserved_charge(
  p_station_id integer,
  p_rider_name text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_station public.charging_stations%rowtype;
  v_rider_name text := btrim(p_rider_name);
begin
  perform public.click_reconcile_station(p_station_id);

  select * into v_station
  from public.charging_stations
  where id = p_station_id
  for update;

  if v_station.slot_status <> 'Reserved'
     or lower(coalesce(v_station.next_rider, v_station.current_rider, '')) <> lower(v_rider_name) then
    raise exception using errcode = 'P0001',
      message = 'This reservation does not belong to this rider or is no longer active.';
  end if;

  if v_station.buffer_end_time is not null
     and v_station.buffer_end_time > now() then
    raise exception using errcode = 'P0001',
      message = 'The transition window is still active. Start charging when the slot opens.';
  end if;

  update public.charging_stations
  set slot_status = 'Charging',
      relay_status = true,
      current_rider = coalesce(next_rider, current_rider),
      next_rider = null,
      buffer_end_time = null,
      slot_start_time = now(),
      slot_end_time = null,
      charge_started_at = now(),
      penalty_status = false,
      updated_at = now()
  where id = p_station_id
  returning * into v_station;

  return jsonb_build_object(
    'station', to_jsonb(v_station),
    'action', 'started',
    'message', 'Charging started. The socket relay is on.'
  );
end;
$$;

create or replace function public.click_finish_charging_session(
  p_station_id integer,
  p_rider_name text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_station public.charging_stations%rowtype;
  v_rider_name text := btrim(p_rider_name);
begin
  perform public.click_reconcile_station(p_station_id);

  select * into v_station
  from public.charging_stations
  where id = p_station_id
  for update;

  if v_station.slot_status <> 'Charging'
     or lower(coalesce(v_station.current_rider, '')) <> lower(v_rider_name) then
    raise exception using errcode = 'P0001',
      message = 'Only the rider with the active charging session can finish it.';
  end if;

  update public.charging_stations
  set slot_status = 'Buffer',
      relay_status = false,
      current_rider = null,
      next_rider = null,
      buffer_end_time = now() + interval '10 minutes',
      slot_end_time = now(),
      charge_started_at = null,
      updated_at = now()
  where id = p_station_id
  returning * into v_station;

  return jsonb_build_object(
    'station', to_jsonb(v_station),
    'action', 'finished',
    'message', 'Session Ended - Transition Window: Please unplug and clear the spot for the next rider. The relay is off for 10 minutes.'
  );
end;
$$;

