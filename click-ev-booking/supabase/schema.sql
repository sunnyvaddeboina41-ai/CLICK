create table if not exists public.charging_stations (
  id integer primary key,
  station_name text not null,
  location text not null default 'Madhapur, Hyderabad',
  relay_status boolean not null default false,
  slot_status text not null default 'Available'
    check (slot_status in ('Charging', 'Buffer', 'Available', 'Reserved')),
  current_rider text,
  next_rider text,
  buffer_end_time timestamptz,
  slot_start_time timestamptz,
  slot_end_time timestamptz,
  charge_started_at timestamptz,
  updated_at timestamptz not null default now(),
  no_show_count integer not null default 0,
  penalty_status boolean not null default false
);

alter table public.charging_stations enable row level security;

alter table public.charging_stations
  add column if not exists location text not null default 'Madhapur, Hyderabad',
  add column if not exists next_rider text,
  add column if not exists slot_start_time timestamptz,
  add column if not exists slot_end_time timestamptz,
  add column if not exists charge_started_at timestamptz,
  add column if not exists updated_at timestamptz not null default now(),
  add column if not exists no_show_count integer not null default 0,
  add column if not exists penalty_status boolean not null default false;

alter table public.charging_stations
  alter column location set default 'Madhapur, Hyderabad';

-- Preserve in-flight reservations when upgrading a table created by an earlier version.
update public.charging_stations
set next_rider = current_rider,
    current_rider = null
where slot_status = 'Reserved'
  and next_rider is null
  and current_rider is not null;

create table if not exists public.rider_penalties (
  id bigint generated by default as identity primary key,
  station_id integer not null references public.charging_stations(id) on delete cascade,
  rider_name text not null,
  rider_name_key text not null,
  reason text not null,
  created_at timestamptz not null default now(),
  penalty_until timestamptz not null
);

-- Upgrade earlier rider_penalties tables before indexing or using the normalized key.
alter table public.rider_penalties
  add column if not exists rider_name_key text;

update public.rider_penalties
set rider_name_key = lower(btrim(rider_name))
where rider_name_key is null;

create index if not exists rider_penalties_rider_until_idx
  on public.rider_penalties (rider_name_key, penalty_until desc);

alter table public.rider_penalties enable row level security;

